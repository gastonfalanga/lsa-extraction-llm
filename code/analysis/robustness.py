import csv
import math
import os
import sys
import random
import subprocess
from collections import Counter, defaultdict

from openpyxl import load_workbook

sys.path.insert(0, os.path.dirname(__file__))

WORKBOOK = "work/audit/audit_sheet.xlsx"
SAMPLE_CSV = "work/audit/audit_sample.csv"
PER_BATCH_CSV = "work/raw_ocr_history/per_batch.csv"
SECOND_PAIRS = "work/second_auditor/verdict_pairs.csv"
OUT = "work/audit/results/robustness.md"
JUDGED = {"Correct", "Wrong"}
ABSENT = "(absent)"
DRAWN = ["initial_position", "initial_orientation", "final_position", "final_orientation"]
EQUIVALENT = ["Palm backward", "Palm outward", "Space in front of torso"]
SEED, N_BOOT = 20261123, 2000


def reference(r):
    if r[8] == "Correct":
        return r[7]
    return r[9] if r[9] not in (None, "") else None


def weighted(items):
    sw = sum(w for w, _ in items)
    return sum(w for w, ok in items if ok) / sw if sw else float("nan")


def boot(rows, weight, rng):
    by_sign = defaultdict(list)
    for s, ok in rows:
        by_sign[s].append(ok)
    signs = list(by_sign)
    stats = []
    for _ in range(N_BOOT):
        pick = [rng.choice(signs) for _ in signs]
        items = [(weight[s], ok) for s in pick for ok in by_sign[s]]
        stats.append(weighted(items))
    stats.sort()
    return stats[int(0.025 * N_BOOT)], stats[int(0.975 * N_BOOT) - 1]


def auroc(scores_pos, scores_neg):
    wins = 0.0
    for p in scores_pos:
        for n in scores_neg:
            wins += 1 if p < n else 0.5 if p == n else 0
    return wins / (len(scores_pos) * len(scores_neg))


def main():
    sample = {r["ocr_id"]: r for r in csv.DictReader(open(SAMPLE_CSV, encoding="utf-8-sig"))}
    wb = load_workbook(WORKBOOK, read_only=True)
    signs = {r[1]: r for r in wb["signs"].iter_rows(min_row=2, values_only=True) if r[0] == "main"}
    weight = {k: float(sample[k]["weight"]) for k in signs}
    all_rows = {i: r for i, r in enumerate(wb["fields"].iter_rows(min_row=2, values_only=True), start=2)}
    fields = [r for r in all_rows.values() if r[1] in signs]
    judged = [r for r in fields if r[8] in JUDGED]
    rng = random.Random(SEED)
    out = ["# Robustness analyses", "", "Generated by `code/analysis/robustness.py`.", ""]

    def cls(r):
        ref = reference(r)
        if r[10] == "Yes":
            return "text"
        if ref in (None, ABSENT):
            return "nothing to extract"
        return "drawing"
    out += ["## 1. Accuracy by provenance of each field", "",
            "| Class | fields | correct | % weighted | 95% CI (sign bootstrap) |", "|---|---|---|---|---|"]
    groups = defaultdict(list)
    for r in judged:
        groups[cls(r)].append(r)
    for g in ("text", "drawing", "nothing to extract"):
        rows = groups[g]
        p = weighted([(weight[r[1]], r[8] == "Correct") for r in rows])
        lo, hi = boot([(r[1], r[8] == "Correct") for r in rows], weight, rng)
        out.append(f"| {g} | {len(rows)} | {sum(r[8] == 'Correct' for r in rows)} | {100 * p:.1f} | "
                   f"{100 * lo:.1f}–{100 * hi:.1f} |")
    by_field_cls = Counter((r[6], cls(r)) for r in judged)
    out += ["", "Fields by type and provenance class (judged fields):", "",
            "| Field | text | drawing | nothing to extract |", "|---|---|---|---|"]
    for f in sorted({r[6] for r in judged}):
        out.append(f"| {f} | {by_field_cls[(f, 'text')]} | {by_field_cls[(f, 'drawing')]} | "
                   f"{by_field_cls[(f, 'nothing to extract')]} |")
    out += ["", "Error types by provenance class (wrong fields):", "",
            "| Error type | text | drawing | nothing to extract |", "|---|---|---|---|"]
    err = Counter((r[11] or "(none)", cls(r)) for r in judged if r[8] == "Wrong")
    for e in sorted({k[0] for k in err}):
        out.append(f"| {e} | {err[(e, 'text')]} | {err[(e, 'drawing')]} | {err[(e, 'nothing to extract')]} |")
    wrong = [r for r in judged if r[8] == "Wrong"]
    out += ["", f"Wrong fields in all: {len(wrong)} (by field type: "
            f"{sum(r[6] not in DRAWN for r in wrong)} written-type, {sum(r[6] in DRAWN for r in wrong)} drawn-type).", ""]

    out += ["## 2. Final states with a real change; non-manual components", ""]
    for f in ("final_position", "final_orientation", "final_configuration"):
        rows = [r for r in judged if r[6] == f and reference(r) not in (None, ABSENT)]
        p = weighted([(weight[r[1]], r[8] == "Correct") for r in rows])
        lo, hi = boot([(r[1], r[8] == "Correct") for r in rows], weight, rng)
        out.append(f"- {f}, reference shows a change: {sum(r[8] == 'Correct' for r in rows)}/{len(rows)} correct, "
                   f"{100 * p:.1f}% weighted (CI {100 * lo:.1f}–{100 * hi:.1f}).")
    for f in ("initial_position", "initial_orientation"):
        rows = [r for r in judged if r[6] == f]
        p = weighted([(weight[r[1]], r[8] == "Correct") for r in rows])
        lo, hi = boot([(r[1], r[8] == "Correct") for r in rows], weight, rng)
        out.append(f"- {f}: {100 * p:.1f}% weighted (sign bootstrap CI {100 * lo:.1f}–{100 * hi:.1f}).")
    nmc = [r for r in judged if r[6] == "non_manual_components"]
    tp = sum(1 for r in nmc if r[7] != ABSENT and r[8] == "Correct")
    fp = sum(1 for r in nmc if r[7] != ABSENT and r[8] == "Wrong")
    fn = sum(1 for r in nmc if r[7] == ABSENT and r[8] == "Wrong")
    tn = sum(1 for r in nmc if r[7] == ABSENT and r[8] == "Correct")
    out += [f"- Non-manual components (per component): {tp} extracted and right, {fp} extracted and wrong, "
            f"{fn} missed, {tn} correctly absent. Precision {100 * tp / max(tp + fp, 1):.1f}%, "
            f"recall {100 * tp / max(tp + fn, 1):.1f}% (unweighted).", ""]

    out += ["## 3. Sensitivity without the equivalences fixed during the audit", ""]
    hit = [r for r in judged if r[8] == "Correct" and any(e in str(r[7]) for e in EQUIVALENT)]
    for g, members in (("drawing-type fields", DRAWN), ("all fields", None)):
        rows = [r for r in judged if members is None or r[6] in members]
        base = weighted([(weight[r[1]], r[8] == "Correct") for r in rows])
        strict = weighted([(weight[r[1]], r[8] == "Correct" and r not in hit) for r in rows])
        out.append(f"- {g}: {100 * base:.1f}% with equivalences, {100 * strict:.1f}% if the "
                   f"{sum(1 for r in hit if members is None or r[6] in members)} fields accepted only through an "
                   "equivalence counted as wrong.")
    out += [f"- Values involved: {dict(Counter(e for r in hit for e in EQUIVALENT if e in str(r[7])))}", ""]

    manner = {(r[1], r[3], r[4], r[5]): str(r[7]) for r in fields if r[6] == "movement_manner"}
    rep_wrong = [r for r in judged if r[6] == "movement_repetition" and r[8] == "Wrong"]
    rub = [r for r in rep_wrong if "Rubbing" in manner.get((r[1], r[3], r[4], r[5]), "") and str(r[7]) == "True"]
    out += ["## 4. Repetition errors and the rubbing rule", "",
            f"- Wrong repetition fields: {len(rep_wrong)}; extracted True with Rubbing in the manner: {len(rub)}.",
            f"- By extracted value: {dict(Counter(str(r[7]) for r in rep_wrong))}.", ""]

    conf = {k: float(sample[k]["ocr_confidence"]) for k in signs}
    per_sign = defaultdict(lambda: [0, 0])
    for r in judged:
        per_sign[r[1]][1] += 1
        per_sign[r[1]][0] += r[8] == "Wrong"
    xs = [conf[k] for k in per_sign]
    ys = [per_sign[k][0] / per_sign[k][1] for k in per_sign]
    mx, my = sum(xs) / len(xs), sum(ys) / len(ys)
    rr = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / math.sqrt(
        sum((x - mx) ** 2 for x in xs) * sum((y - my) ** 2 for y in ys))
    z, se = math.atanh(rr), 1 / math.sqrt(len(xs) - 3)
    pos = [conf[r[1]] for r in judged if r[8] == "Wrong"]
    neg = [conf[r[1]] for r in judged if r[8] == "Correct"]
    out += ["## 5. Calibration of self-reported confidence", "",
            f"- Pearson r (confidence vs per-sign error rate) = {rr:.2f}, 95% CI {math.tanh(z - 1.96 * se):.2f} to "
            f"{math.tanh(z + 1.96 * se):.2f} ({len(xs)} signs).",
            f"- AUROC of confidence for telling wrong fields from correct ones (lower confidence = predicted wrong): "
            f"{auroc(pos, neg):.2f} ({len(pos)} wrong, {len(neg)} correct fields; 0.5 = no information).", ""]

    pairs = list(csv.DictReader(open(SECOND_PAIRS, encoding="utf-8")))
    desc = [p for p in pairs if p["arm"] == "describe" and p["second_auditor_verdict"] in JUDGED
            and p["first_auditor_verdict"] in JUDGED]
    m_a1 = sum(p["first_auditor_verdict"] == "Correct" for p in desc) / len(desc)
    m_a2 = sum(p["second_auditor_verdict"] == "Correct" for p in desc) / len(desc)
    a1_a2 = sum(p["first_auditor_verdict"] == p["second_auditor_verdict"] for p in desc) / len(desc)
    out += ["## 6. Agreement triangle on the second auditor's blind signs", "",
            f"On {len(desc)} drawn fields judged by both auditors (28 signs):", "",
            f"- model vs first auditor: {100 * m_a1:.1f}% (share of extracted values the first auditor accepted);",
            f"- model vs second auditor: {100 * m_a2:.1f}%;",
            f"- first vs second auditor: {100 * a1_a2:.1f}% agreement on whether the extracted value is right.", "",
            "| Field | model vs A1 | model vs A2 | A1 vs A2 | n |", "|---|---|---|---|---|"]
    for f in DRAWN:
        d = [p for p in desc if p["field"] == f]
        if d:
            out.append(f"| {f} | {100 * sum(p['first_auditor_verdict'] == 'Correct' for p in d) / len(d):.1f}% | "
                       f"{100 * sum(p['second_auditor_verdict'] == 'Correct' for p in d) / len(d):.1f}% | "
                       f"{100 * sum(p['first_auditor_verdict'] == p['second_auditor_verdict'] for p in d) / len(d):.1f}% "
                       f"| {len(d)} |")
    from second_auditor_results import RETURNED, palm, pos
    norm = {"initial_position": pos, "final_position": pos, "initial_orientation": palm, "final_orientation": palm}
    same, total = Counter(), Counter()
    for r in load_workbook(RETURNED, read_only=True)["describir"].iter_rows(min_row=2, values_only=True):
        if r[0] is None or (r[5] or "").strip().lower() == "no":
            continue
        keys = {all_rows[int(k)][6]: int(k) for k in str(r[12]).split(";")}
        ref = {f: reference(all_rows[k]) for f, k in keys.items()}
        if None in ref.values() or any(all_rows[k][8] not in JUDGED for k in keys.values()):
            continue
        a2 = {"initial_position": r[6], "initial_orientation": r[7], "final_position": r[9], "final_orientation": r[10]}
        for f in ("final_position", "final_orientation"):
            init = f.replace("final", "initial")
            if ref[f] == ABSENT:
                ref[f] = ref[init]
            if a2[f] in (None, "", "(sin cambio)"):
                a2[f] = a2[init]
        for f in DRAWN:
            total[f] += 1
            same[f] += norm[f](ref[f]) == norm[f](a2[f])
    out += ["", "Readings of the drawing (first auditor's reference value against the second auditor's description):",
            ""] + [f"- {f}: {same[f]}/{total[f]} ({100 * same[f] / total[f]:.1f}%)" for f in DRAWN] + [
            f"- all drawn fields: {sum(same.values())}/{sum(total.values())} "
            f"({100 * sum(same.values()) / sum(total.values()):.1f}%)"]
    sign_of = {i: r[1] for i, r in all_rows.items()}
    acc = defaultdict(lambda: [0, 0])
    arm = {}
    for p in pairs:
        if p["second_auditor_verdict"] in JUDGED and p["first_auditor_verdict"] in JUDGED:
            s = sign_of[int(p["fields_row"])]
            arm[s] = p["arm"]
            acc[s][1] += 1
            acc[s][0] += p["second_auditor_verdict"] == "Correct"
    groups2 = defaultdict(list)
    for s, (c, n) in acc.items():
        groups2[arm[s]].append(c / n)

    def sd(v):
        m = sum(v) / len(v)
        return math.sqrt(sum((x - m) ** 2 for x in v) / (len(v) - 1))
    n1, n2 = len(groups2["verify"]), len(groups2["describe"])
    pooled = math.sqrt(((n1 - 1) * sd(groups2["verify"]) ** 2 + (n2 - 1) * sd(groups2["describe"]) ** 2) / (n1 + n2 - 2))
    mde = (1.96 + 0.84) * pooled * math.sqrt(1 / n1 + 1 / n2)
    out += ["", f"- Minimum detectable difference of the randomized check (two-sided 5%, power 80%, per-sign "
            f"accuracy, SD {100 * pooled:.1f} points, {n1} + {n2} signs): about {100 * mde:.0f} points.", ""]

    rescanned = set()
    for r in csv.DictReader(open(PER_BATCH_CSV, encoding="utf-8-sig")):
        log = subprocess.run(["git", "log", "--all", "--format=%h", "--", f"data/processed/{r['batch']}"],
                             capture_output=True, text=True).stdout.split()
        if r["first_commit"] in log and log.index(r["first_commit"]) < len(log) - 1:
            rescanned.add("v1_" + r["batch"].replace(".json", ".pdf"))
    out += ["## 7. Batches whose evaluated scan replaced an earlier committed scan", "",
            f"{len(rescanned)} batches. Audited signs in them: "
            f"{sum(1 for k in signs if signs[k][3] in rescanned)}.", "",
            "| Batches | signs | fields | % weighted |", "|---|---|---|---|"]
    for name, pred in (("replaced an earlier scan", lambda k: signs[k][3] in rescanned),
                       ("first committed scan", lambda k: signs[k][3] not in rescanned)):
        rows = [r for r in judged if pred(r[1])]
        out.append(f"| {name} | {len({r[1] for r in rows})} | {len(rows)} | "
                   f"{100 * weighted([(weight[r[1]], r[8] == 'Correct') for r in rows]):.1f} |")
    hv = Counter(signs[k][10] for k in signs)
    out += ["", f"Hand-count verdicts on the 150 signs: {dict(hv)} (None = not marked, counted as Correct).", ""]

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
